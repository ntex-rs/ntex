    fn test_io_error() {
        assert_eq!(
            StatusCode::NOT_FOUND,
            WebResponseError::error_response(
                &mut io::Error::new(io::ErrorKind::NotFound, ""),
                &(),
            )
            .status(),
        );
        assert_eq!(
            StatusCode::FORBIDDEN,
            WebResponseError::error_response(
                &mut io::Error::new(io::ErrorKind::PermissionDenied, ""),
                &(),
            )
            .status(),
        );
        assert_eq!(
            StatusCode::INTERNAL_SERVER_ERROR,
            WebResponseError::error_response(&mut io::Error::other(""), &(),).status(),
        );
    }

