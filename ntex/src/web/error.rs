    #[test]
    fn test_handshake_error() {
        use crate::ws::error::HandshakeError;

        let resp = WebResponseError::<_, DefaultError>::error_response(
            &mut HandshakeError::GetMethodRequired,
            &(),
        );
        assert_eq!(resp.status(), StatusCode::METHOD_NOT_ALLOWED);
        let resp = WebResponseError::<_, DefaultError>::error_response(
            &mut HandshakeError::NoWebsocketUpgrade,
            &(),
        );
        assert_eq!(resp.status(), StatusCode::BAD_REQUEST);
        let resp = WebResponseError::<_, DefaultError>::error_response(
            &mut HandshakeError::NoConnectionUpgrade,
            &(),
        );
        assert_eq!(resp.status(), StatusCode::BAD_REQUEST);
        let resp = WebResponseError::<_, DefaultError>::error_response(
            &mut HandshakeError::NoVersionHeader,
            &(),
        );
        assert_eq!(resp.status(), StatusCode::BAD_REQUEST);
        let resp = WebResponseError::<_, DefaultError>::error_response(
            &mut HandshakeError::UnsupportedVersion,
            &(),
        );
        assert_eq!(resp.status(), StatusCode::BAD_REQUEST);
        let resp = WebResponseError::<_, DefaultError>::error_response(
            &mut HandshakeError::BadWebsocketKey,
            &(),
        );
        assert_eq!(resp.status(), StatusCode::BAD_REQUEST);
    }

