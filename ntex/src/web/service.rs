/// Factory of web services that can be registered with an application or scope.
///
/// `App::service()` and `Scope::service()` accept any `WebServiceFactory`.
/// It is implemented by [`Resource`](crate::web::Resource),
/// [`Scope`](crate::web::Scope), services generated by the route attribute
/// macros, and services built with `web::service()`.
pub trait WebServiceFactory<St: State, In>: 'static {
    /// Register the service, its path, and its guards in `config`.
    fn register(self, config: &mut WebServiceConfig<St, In>);
}

pub(super) trait AppServiceFactory<St: State, In> {
    fn register(&mut self, config: &mut WebServiceConfig<St, In>);
}

pub(super) struct ServiceFactoryWrapper<T> {
    factory: Option<T>,
}

impl<T> ServiceFactoryWrapper<T> {
    pub(super) fn new(factory: T) -> Self {
        Self {
            factory: Some(factory),
        }
    }
}

impl<T, St, In> AppServiceFactory<St, In> for ServiceFactoryWrapper<T>
where
    T: WebServiceFactory<St, In>,
    St: State,
{
    fn register(&mut self, config: &mut WebServiceConfig<St, In>) {
        if let Some(item) = self.factory.take() {
            item.register(config);
        }
    }
}

type Guards = Vec<Box<dyn Guard>>;

/// Application service configuration
#[derive(derive_more::Debug)]
#[debug("WebServiceConfig")]
pub struct WebServiceConfig<St: State, In = ()> {
    root: bool,
    services: Vec<(
        ResourceDef,
        HttpService<St, In>,
        Option<Guards>,
        Option<Rc<ResourceMap>>,
    )>,
}

impl<St: State, In: 'static> WebServiceConfig<St, In> {
    /// Create server settings instance
    pub(crate) fn new() -> Self {
        WebServiceConfig {
            root: true,
            services: Vec::new(),
        }
    }

    /// Check if root is being configured
    pub fn is_root(&self) -> bool {
        self.root
    }

    pub(crate) fn into_services(
        self,
    ) -> Vec<(
        ResourceDef,
        HttpService<St, In>,
        Option<Guards>,
        Option<Rc<ResourceMap>>,
    )> {
        self.services
    }

    /// Register http service
    pub fn register_service<S>(
        &mut self,
        rdef: ResourceDef,
        guards: Option<Vec<Box<dyn Guard>>>,
        nested: Option<Rc<ResourceMap>>,
        factory: impl IntoServiceFactory<S, St, WebRequest<In>>,
    ) where
        S: ServiceFactory<
                St,
                WebRequest<In>,
                Res = WebResponse,
                Error = WebError<St, St::Error>,
                InitError = Failure,
            > + 'static,
    {
        self.services
            .push((rdef, boxed::factory(factory.into_factory()), guards, nested));
    }
}

/// Create service adapter for a specific path.
///
/// ```rust
/// use std::convert::Infallible;
/// use ntex::web::{self, guard, App, HttpResponse};
///
/// async fn my_service(req: web::WebRequest<()>) -> Result<web::WebResponse, Infallible> {
///     Ok(req.into_response(HttpResponse::Ok().build()))
/// }
///
/// let app = App::default().service(
///     web::service("/users/*")
///         .guard(guard::Header("content-type", "text/plain"))
///         .build(my_service)
/// );
/// ```
#[derive(Debug)]
pub struct WebServiceAdapter {
    rdef: Vec<String>,
    name: Option<String>,
    guards: AllGuard,
    methods: HashSet<Method>,
}

impl WebServiceAdapter {
    #[must_use]
    #[allow(clippy::needless_pass_by_value)]
    /// Create new `WebServiceAdapter` instance.
    pub fn new<T: IntoPattern>(path: T) -> Self {
        WebServiceAdapter {
            rdef: path.patterns(),
            name: None,
            guards: AllGuard::default(),
            methods: HashSet::default(),
        }
    }

    /// Set service name.
    ///
    /// Name is used for url generation.
    #[must_use]
    pub fn name(mut self, name: &str) -> Self {
        self.name = Some(name.to_string());
        self
    }

    /// Add a match guard to this web service.
    ///
    /// The service is selected only when its path and all registered guards
    /// match. If a guard rejects the request, the router can try another
    /// matching service; otherwise the containing scope or application fallback
    /// is used.
    ///
    /// ```rust
    /// use std::convert::Infallible;
    /// use ntex::web::{self, guard, App, HttpResponse};
    ///
    /// async fn index(
    ///     req: web::WebRequest<()>,
    /// ) -> Result<web::WebResponse, Infallible> {
    ///     Ok(req.into_response(HttpResponse::Ok().build()))
    /// }
    ///
    /// App::default().service(
    ///     web::service("/health")
    ///         .guard(guard::Get())
    ///         .guard(guard::Header("x-health-check", "true"))
    ///         .build(index)
    /// );
    /// ```
    #[must_use]
    pub fn guard<G: Guard + 'static>(mut self, guard: G) -> Self {
        self.guards.add(guard);
        self
    }

    /// Add a supported method to this service.
    ///
    /// Repeated calls allow any of the registered methods. If this method is
    /// never called, no method check is added and existing guard and service
    /// behavior is unchanged.
    ///
    /// Methods are checked after the path and all guards match, but before the
    /// service is called. An unsupported method returns `405 Method Not Allowed`
    /// with an `Allow` header; the router does not try another service or fallback.
    /// Use a method guard instead when a mismatch should continue routing.
    ///
    /// ```rust
    /// use std::convert::Infallible;
    /// use ntex::http::Method;
    /// use ntex::web::{self, guard, App, HttpResponse};
    ///
    /// async fn index(
    ///     req: web::WebRequest<()>,
    /// ) -> Result<web::WebResponse, Infallible> {
    ///     Ok(req.into_response(HttpResponse::Ok().build()))
    /// }
    ///
    /// App::default().service(
    ///     web::service("/health")
    ///         .method(Method::GET)
    ///         .guard(guard::Header("x-health-check", "true"))
    ///         .build(index)
    /// );
    /// ```
    #[must_use]
    pub fn method(mut self, method: Method) -> Self {
        self.methods.insert(method);
        self
    }

    /// Set a service factory implementation and generate web service.
    pub fn build<Sf, St, In, F>(self, service: F) -> impl WebServiceFactory<St, In>
    where
        St: State,
        In: 'static,
        F: IntoServiceFactory<Sf, St, WebRequest<In>>,
        Sf: ServiceFactory<St, WebRequest<In>, Res = WebResponse> + 'static,
        Sf::Error: WebResponseError<St, St::Error>,
        Sf::InitError: IntoFailure,
    {
        WebServiceImpl {
            srv: service
                .into_factory()
                .map_err(WebError::from_err)
                .map_init_err(IntoFailure::fail),
            rdef: self.rdef,
            name: self.name,
            guards: self.guards,
            methods: self.methods,
            ph: PhantomData,
        }
    }
}

struct WebServiceImpl<Sf, In> {
    srv: Sf,
    rdef: Vec<String>,
    name: Option<String>,
    guards: AllGuard,
    methods: HashSet<Method>,
    ph: PhantomData<In>,
}

impl<Sf, In, St> WebServiceFactory<St, In> for WebServiceImpl<Sf, In>
where
    St: State,
    In: 'static,
    Sf: ServiceFactory<
            St,
            WebRequest<In>,
            Res = WebResponse,
            Error = WebError<St, St::Error>,
            InitError = Failure,
        > + 'static,
{
    fn register(mut self, config: &mut WebServiceConfig<St, In>) {
        let guards = if self.guards.0.is_empty() {
            None
        } else {
            Some(std::mem::take(&mut self.guards.0))
        };

        let mut rdef = if config.is_root() || !self.rdef.is_empty() {
            ResourceDef::new(insert_slash(self.rdef))
        } else {
            ResourceDef::new(self.rdef)
        };
        if let Some(name) = self.name {
            rdef.set_name(name);
        }
        if self.methods.is_empty() {
            config.register_service(rdef, guards, None, self.srv);
        } else {
            let mut allow: Vec<_> = self.methods.iter().map(Method::as_str).collect();
            allow.sort_unstable();
            let allow = allow.join(", ");
            let methods = Rc::new(self.methods);

            let service = crate::factory(async move |req: WebRequest<In>| {
                if methods.contains(&req.head().method) {
                    Ok(req)
                } else {
                    Err(WebError::from_err(InternalError::from_response(
                        "Method not allowed",
                        Response::MethodNotAllowed()
                            .header(header::ALLOW, allow.as_str())
                            .build(),
                    )))
                }
            })
            .map_init_err(|_| unreachable!())
            .and_then(self.srv);

            config.register_service(rdef, guards, None, service);
        }
    }
}

#[allow(unused_parens)]
impl<T, St, In> WebServiceFactory<St, In> for Vec<T>
where
    T: WebServiceFactory<St, In> + 'static,
    St: State,
{
    fn register(mut self, config: &mut WebServiceConfig<St, In>) {
        for service in self.drain(..) {
            service.register(config);
        }
    }
}

macro_rules! tuple_web_service(
    {$(#[$meta:meta])* $(($n:tt, $T:ident)),+} => {

        $(#[$meta])*
        impl<St: State, In, $($T: WebServiceFactory<St, In> + 'static),+> WebServiceFactory<St, In> for ($($T,)+) {
            fn register(self, config: &mut WebServiceConfig<St, In>) {
                $(
                    self.$n.register(config);
                )+
            }
        }
    }
);

impl<St, In, T, const N: usize> WebServiceFactory<St, In> for [T; N]
where
    St: State,
    T: WebServiceFactory<St, In> + 'static,
{
    fn register(self, config: &mut WebServiceConfig<St, In>) {
        for t in self {
            t.register(config);
        }
    }
}

